const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');

const source = process.argv[2];
if (!source) throw new Error('Pass the original 소망생물들 directory.');
const root = path.resolve(__dirname, '..');
const prompts = JSON.parse(fs.readFileSync(path.join(source, 'video_prompts.json'), 'utf8'));
const captions = JSON.parse(fs.readFileSync(path.join(source, 'caption_data.json'), 'utf8'));
const promptMap = new Map(prompts.map(row => [row.folder, row]));
const categories = ['경제적 소망','관계적 소망','자기실현 소망','건강·생존 소망','성장 소망','자유 소망','인정 소망'];
const groups = [['그냥하기 (신속형)','때를 기다리기'],['낯선 환경 진입형','비교 테스트형','체험 샘플링형'],['기록 축적형','반복 훈련형','저장 비축형'],['느린 재시작형','보호막 재생형','속도 조절형'],['역할 분담형','함께 루틴형','환경 적응형'],['내면 압축형','심해 잠수형'],['관점 전환형','한계 돌파형','형태 전환형']];
const entries = [];
fs.mkdirSync(path.join(root, 'assets', 'catalog'), { recursive:true });
for (const dir of fs.readdirSync(source, {withFileTypes:true}).sort((a,b)=>a.name.localeCompare(b.name,'ko'))) {
  if (!dir.isDirectory()) continue;
  const folder = path.join(source, dir.name);
  const resultFile = path.join(folder,'video_result.json');
  if (!fs.existsSync(resultFile)) continue;
  const pngs = fs.readdirSync(folder).filter(name=>/\.png$/i.test(name));
  if (pngs.length !== 1) throw new Error(`Expected one PNG: ${dir.name}`);
  const result = JSON.parse(fs.readFileSync(resultFile,'utf8'));
  const url = new URL(result.video_url);
  if (url.protocol !== 'https:') throw new Error(`Invalid video URL: ${dir.name}`);
  const meta = promptMap.get(dir.name);
  if (!meta || !dir.name.startsWith(meta.creatureTitle + '_') || !dir.name.endsWith('_' + meta.methodTitle)) throw new Error(`Missing or mismatched planning metadata: ${dir.name}`);
  const situationIndex = categories.indexOf(meta.wishCat);
  const wayIndex = groups.findIndex(group=>group.includes(meta.methodTitle));
  if (situationIndex < 0 || wayIndex < 0) throw new Error(`Unmapped axis: ${dir.name}`);
  const id = 'WC-' + crypto.createHash('sha256').update(dir.name,'utf8').digest('hex').slice(0,12);
  const bytes = fs.readFileSync(path.join(folder,pngs[0]));
  const imagePath = `assets/catalog/${id}.png`;
  fs.copyFileSync(path.join(folder,pngs[0]),path.join(root,imagePath));
  entries.push({id,folder:dir.name,wishType:meta.creatureTitle,methodType:meta.methodTitle,wishCategory:meta.wishCat,situationIndex,wayIndex,imageUrl:imagePath,videoUrl:result.video_url,sourcePng:pngs[0],imageSha256:crypto.createHash('sha256').update(bytes).digest('hex'),caption:captions[dir.name] ? [captions[dir.name].line1,captions[dir.name].line2].filter(Boolean).join(' ') : ''});
}
if (entries.length !== 438 || new Set(entries.map(e=>e.id)).size !== 438) throw new Error(`Catalog count/uniqueness changed: ${entries.length}`);
const catalog = {version:'2026-10-22',count:entries.length,selectionPolicy:'Only a direct combination folder containing exactly one PNG and video_result.json; PNG bytes preserved; source video URL preserved; no synthetic result.',categories,methodGroups:groups,entries};
fs.writeFileSync(path.join(root,'creature-catalog.json'),JSON.stringify(catalog,null,2)+'\n');
fs.writeFileSync(path.join(root,'creature-catalog.js'),'/* Generated by scripts/import-creatures.cjs. Source of truth: creature-catalog.json. */\nwindow.WISH_CREATURE_CATALOG = '+JSON.stringify(catalog)+';\n');
const summary = ['# 소망생물 결과 연결 기록','',`기준일: ${catalog.version}`,`총 ${entries.length}개 조합. 원본 PNG와 같은 폴더의 video_result.json 영상 주소를 1:1 연결.`, '', '원본 PNG의 색상·형태·밝기를 수정하지 않음. 여분·임시·변환 폴더 제외.','소망 대분류는 video_prompts.json의 wishCat을 사용. caption_data.json의 불완전한 대분류로 덮어쓰지 않음.','실제 존재하는 세부 조합만 최종 선택 가능. 없는 조합을 다른 생물로 자동 대체하지 않음.','안정적인 WC ID는 폴더명 SHA-256 앞 12자리. 전체 원본 파일명·해시·영상 주소는 creature-catalog.json에 기록.','','|소망 대분류|조합 수|','|---|---:|',...categories.map(c=>`|${c}|${entries.filter(e=>e.wishCategory===c).length}|`),'','|ID|폴더 / 소망 세부유형 × 실현 세부방식|','|---|---|',...entries.map(e=>`|${e.id}|${e.folder}|`),''];
fs.writeFileSync(path.join(root,'CREATURE-MAPPING.md'),summary.join('\n'));
console.log(JSON.stringify({count:entries.length,categories:categories.map(c=>({category:c,count:entries.filter(e=>e.wishCategory===c).length})),totalPngBytes:entries.reduce((n,e)=>n+fs.statSync(path.join(root,e.imageUrl)).size,0)}));
